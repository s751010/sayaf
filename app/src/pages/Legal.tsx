const IDENTITY_TODO = true;

function Section({ title, children }: { title: string; children: ReactNode }) {
  return (
    <section className="mt-9">
      <h2 className="font-display text-xl font-extrabold text-ink">{title}</h2>
      <div className="mt-3 flex flex-col gap-3 leading-relaxed text-dim">{children}</div>
    </section>
  );
}

function Bullets({ items }: { items: string[] }) {
  return (
    <ul className="flex list-none flex-col gap-2">
      {items.map((t) => (
        <li key={t} className="flex gap-2.5">
          <span aria-hidden="true" className="mt-2 h-1.5 w-1.5 shrink-0 rounded-full bg-gold" />
          <span>{t}</span>
        </li>
      ))}
    </ul>
  );
}

function Identity() {
  if (!IDENTITY_TODO) return null;
  return (
    <div className="mt-9 rounded-2xl border border-line-gold bg-gold/[.06] p-5">
      <p className="text-sm font-black text-ink">بيانات المنشأة</p>
      <p className="mt-2 text-sm leading-relaxed text-dim">
        الاسم النظامي ورقم السجل التجاري والرقم الضريبي والعنوان الوطني — تُستكمل
        قبل تفعيل التحصيل التجاري. حتى ذلك الحين، وسيلة التواصل المعتمدة هي بريد
        الدعم وواتساب الدعم الموضّحان في تذييل الموقع.
      </p>
    </div>
  );
}

function Shell({
  title,
  intro,
  children,
}: {
  title: string;
  intro: string;
  children: ReactNode;
}) {
  return (
    <div className="flex min-h-dvh flex-col">
      <Navbar />
      <main className="mx-auto w-full max-w-3xl flex-1 px-5 py-12">
        <h1 className="font-display text-3xl font-black text-ink">{title}</h1>
        <p className="mt-3 leading-relaxed text-dim">{intro}</p>
        <p className="mt-2 text-xs text-faint">آخر تحديث: {UPDATED}</p>
        {children}
        <Identity />
        <p className="mt-9 text-sm text-dim">
          للأسئلة:{" "}
          <Link to="/help" className="font-bold text-gold hover:underline">
            مركز المساعدة
          </Link>{" "}
          · أو راسل الدعم من التذييل أدناه.
        </p>
      </main>
      <Footer />
    </div>
  );
}

