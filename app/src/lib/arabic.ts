/**
 * توحيد الكتابة العربية للمطابقة — لا للعرض.
 *
 * الزبون يكتب «قهوه» والتاجر «قهوة»، ويكتب «حمص» والتاجر «حمّص»: البحث بالحرف
 * كان يُرجع صفراً للاثنين. فيمرّ النصّان كلاهما هنا قبل المقارنة: تُنزع
 * الحركات والتطويل، وتُوحَّد الهمزات على الألف، والتاء المربوطة هاءً، والألف
 * المقصورة ياءً — الأخطاء التي يقع فيها كل من يكتب على جوّال.
 */
export function normalizeAr(s: string): string {
  return s
    .toLowerCase()
    .replace(/[ً-ْٰـ]/g, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ة/g, "ه")
    .replace(/ى/g, "ي")
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    .trim();
}
