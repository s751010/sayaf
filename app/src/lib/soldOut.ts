/**
 * «نفد اليوم» — حكمٌ واحد على الطبق النافد، تقرؤه كلّ قطعة في المنيو.
 *
 * ═══ ما تغيّر (٢٠٢٦/١٠/٢٦، بموافقة المالك) ═══
 *
 * كان الطبق الذي يُطفئه التاجر يُرشَّح من الاستعلام العامّ فيختفي من المنيو.
 * والزبون الذي جاء من أجله لا يعرف أنه نفد اليوم وسيعود غداً — يظنّه حُذف. الآن
 * يصل الطبق ويُعرض **بشارة، في آخر قسمه، بلا زرّ إضافة، ولا يكون «طبق اليوم»**.
 *
 * ═══ لماذا ملفٌّ مستقلّ ═══
 *
 * السؤال «هل يُطلب هذا الطبق؟» يُسأل في خمسة مواضع (البطاقة · زرّ الإضافة ·
 * نافذة الطبق · السلّة · طبق اليوم وغلاف القسم). وشرطٌ مكتوب بيدٍ في كلٍّ منها
 * يتباعد: أحدها يقرأ `!d.available` فيُسقط الصفوف القديمة التي تحمل `null` —
 * وهي **متاحة** (العمود أُضيف بعدها، واللوحة تقرؤها `?? true`).
 *
 * كلّها **خالصة**: بلا حالة ولا شبكة ولا DOM.
 */
import type { Dish } from "@/lib/types";

/**
 * نفد؟ — **`false` الصريحة وحدها**. `null` صفٌّ قديم قبل العمود وهو متاح،
 * تماماً كما يقرؤه التاجر في لوحته (`d.available ?? true`).
 */
export function isSoldOut(d: Pick<Dish, "available"> | null | undefined): boolean {
  return d?.available === false;
}

/**
 * النافد إلى آخر قسمه — **ترتيبٌ ثابت** لما عداه.
 *
 * الخادم رتّب الأطباق بترتيب التاجر (`sort_order` ثم `created_at`)، فالمتاح
 * يبقى بالترتيب نفسه والنافد يتبعه بالترتيب نفسه. والزبون يمسح القسم من أعلاه:
 * طبقٌ لا يُطلب في أوّله يأخذ مكان ما يُطلب.
 *
 * يُعيد مصفوفة جديدة ولا يمسّ المُدخَلة.
 */
export function soldOutLast<T extends Pick<Dish, "available">>(dishes: readonly T[]): T[] {
  return [...dishes.filter((d) => !isSoldOut(d)), ...dishes.filter(isSoldOut)];
}

/**
 * نصّ الشارة. **واحدٌ في كل الطوابع** — الطابع يغيّر شكلها لا كلامها
 * (`.m-soldout` في `menu-skins.css`): «نفد اليوم» تقول للزبون إن الطبق باقٍ في
 * القائمة ويعود، و«غير متوفّر» وحدها تُقرأ «حُذف».
 */
export function soldOutLabel(en: boolean): string {
  return en ? "Sold out today" : "نفد اليوم";
}

/**
 * خريطة ما **يُطلب** — للسلّة وحدها.
 *
 * ⚠️ السلّة تعامل الطبق الغائب عن خريطتها «لم يعد متاحاً» وتحجب الإرسال
 * (`CartReview`: `missing`). وكان ذلك صحيحاً حين كان النافد لا يصل أصلاً. الآن
 * يصل، فلو أُعطيت خريطة كلّ الأطباق لصار سطرٌ محفوظ لطبقٍ نفد **يُرسَل** —
 * والخادم يرفضه بعد أن ينتظر الزبون. فالسلّة تأخذ هذه، وبلا مسّ ملفّها.
 */
export function orderableById<T extends Pick<Dish, "id" | "available">>(
  dishes: readonly T[]
): Map<string, T> {
  return new Map(dishes.filter((d) => !isSoldOut(d)).map((d) => [d.id, d] as const));
}
