/**
 * الرمز الأقرب لنصٍّ حرّ (اسم طبق أو تصنيف)، أو `null` إن لم نعرفه.
 *
 *   guessGlyph("مندي دجاج")        // "kabsa"
 *   guessGlyph("سمك سلمون بالليمون") // "fish"
 *   guessGlyph("آيس لاتيه")         // "icedcup"
 */
export function guessGlyph(text: string | null | undefined): IconName | null {
  const t = norm(text ?? "");
  if (!t) return null;
  const words = t.split(" ").flatMap(forms);
  for (const [icon, keys] of HINTS) {
    for (const key of keys) {
      if (key.includes(" ") ? t.includes(key) : words.some((w) => hit(w, key))) return icon;
    }
  }
  return null;
}
