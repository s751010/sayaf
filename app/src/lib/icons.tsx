/* ══ السجلّ الموحّد ═══════════════════════════════════════════════════ */

export const GLYPHS: Record<string, Glyph> = { ...UI, ...FOOD };
export type IconName = keyof typeof UI | keyof typeof FOOD;

/** أسماء رموز الطعام وحدها — يستعملها مُنتقي رمز الطبق. */
export const FOOD_NAMES = Object.keys(FOOD) as (keyof typeof FOOD)[];

const VIEW = 24;
const STROKE = 1.75;

/* ══ العرض في الـDOM ══════════════════════════════════════════════════ */

export function Icon({
  name,
  size = 20,
  className,
  strokeWidth = STROKE,
}: {
  name: IconName | string;
  size?: number;
  className?: string;
  strokeWidth?: number;
}) {
  const g = GLYPHS[name];
  if (!g) return null;
  return (
    <svg
      viewBox={`0 0 ${VIEW} ${VIEW}`}
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={strokeWidth}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      // الانعكاس بـCSS لا بـtransform مضمَّن: القاعدة في `global.css` تقرأ
      // `[dir="rtl"]` من السلف، فتصحّ الأيقونة داخل جزيرة LTR أيضاً.
      className={g.flip ? `cm-icon-flip ${className ?? ""}` : className}
      style={{ flexShrink: 0 }}
    >
      {g.s?.map((d, i) => (
        <path key={`s${i}`} d={d} />
      ))}
      {g.f?.map((d, i) => (
        <path key={`f${i}`} d={d} fill="currentColor" stroke="none" />
      ))}
    </svg>
  );
}

/* ══ الرسم على canvas ═════════════════════════════════════════════════
 *
 * ⚠️ هذه الدالة هي سبب أن الأيقونات مسارات نصّية لا JSX: `renderCard` تعمل
 * على `canvas` بـ٣٠٠DPI، وكان الرمز يُكتب هناك بـ`fillText` فيأتي من خطّ
 * النظام — فيختلف المطبوع عن المعاين. الآن المصدر واحد للاثنين.
 */

/** يرسم أيقونة بمركز (cx,cy) وحجم `size` بكسلاً. */
export function paintIcon(
  ctx: CanvasRenderingContext2D,
  name: IconName | string,
  cx: number,
  cy: number,
  size: number,
  color: string,
  opts: { flip?: boolean; weight?: number } = {}
): boolean {
  const g = GLYPHS[name];
  if (!g) return false;
  const k = size / VIEW;
  ctx.save();
  ctx.translate(cx, cy);
  // الانعكاس صريح هنا: اللوحة لا تعرف `dir`.
  if (opts.flip && g.flip) ctx.scale(-1, 1);
  ctx.scale(k, k);
  ctx.translate(-VIEW / 2, -VIEW / 2);
  ctx.strokeStyle = color;
  ctx.fillStyle = color;
  ctx.lineWidth = opts.weight ?? STROKE;
  ctx.lineCap = "round";
  ctx.lineJoin = "round";
  for (const d of g.s ?? []) ctx.stroke(new Path2D(d));
  for (const d of g.f ?? []) ctx.fill(new Path2D(d));
  ctx.restore();
  return true;
}

/* ══ رمز الطبق: «cm:» مع إبقاء الإيموجي القديم يعمل ═══════════════════
 *
 * `dishes.emoji` عمود نصّي فيه إيموجي عند كل مطعم قائم. فلا يجوز أن يتغيّر
 * منيو أحد من تحته — نفس منطق `aliasType` مع `restaurants.type`.
 */

const PREFIX = "cm:";

export function iconValue(name: IconName | string): string {
  return PREFIX + name;
}

/** يعيد اسم الرمز إن كانت القيمة من مجموعتنا، وإلا `null` (إيموجي أو فارغ). */
export function iconNameOf(value: string | null | undefined): IconName | null {
  if (!value?.startsWith(PREFIX)) return null;
  const name = value.slice(PREFIX.length);
  return name in GLYPHS ? (name as IconName) : null;
}

/**
 * رمز الطبق كما يُعرض — **القارئ الوحيد لـ`dishes.emoji`**.
 *
 * وجوده في مكان واحد هو ما يجعل التسامح مع القديم رخيصاً: أي شاشة تعرض رمز
 * طبق تنادي هذه، فلا يبقى موضع يفترض أن القيمة إيموجي دائماً. ومعرّف من
 * مجموعتنا حُذف لاحقاً يسقط إلى نصّه لا إلى فراغ.
 */
export function DishGlyph({
  value,
  size = 24,
  className,
}: {
  value: string | null | undefined;
  size?: number;
  className?: string;
}) {
  const name = iconNameOf(value);
  if (name) return <Icon name={name} size={size} className={className} />;
  return (
    <span className={className} style={{ fontSize: size, lineHeight: 1 }} aria-hidden="true">
      {value?.trim() || "🍽"}
    </span>
  );
}
