/**
 * الشارة التي يجب أن يحملها أوّل الصفّ — الفطور مكانٌ شعبي، والشاورما مشويات. والبيتزا
 * «مطعم»: شارة «مطعم سريع» توجب أن يكون «ريحان» بين ثلاثته (قاعدة ٢)، ولا مكان فيها إلا
 * بإخراج «نيون» أو «فاتورة» بلا شارةٍ تبقى لهما.
 *
 * والقهوة «كافيه» (٠٧/١١) — والكافيه الشعبي معها يومها. ثم (٠٩/١١) امتلأ الكافيه بأشكال القهوة،
 * فرجعت «دلّة» إلى «شعبي» ومعها صفّاها (الكافيه الشعبي والقهوة العربية): مع الحدّ أربعة لها مقعدٌ
 * في الشعبي بلا إخراج «دكّان» ولا «فوّال». وكشك القهوة السريع «عصائر» — شارة «درايف».
 *
 * وبيت الشاي (٠٧/١١) «شاي» — شارة «سماور» نفسها.
 */
export function badgeTypeOf(key: string): string {
  if (key === SPECIALTY || key === BREW_BAR) return "كافيه";
  // ٠٩/١١: «دلّة» شارتها «شعبي» — والكافيه الشعبي والقهوة العربية أوّلهما «دلّة».
  if (key === POPULAR_CAFE || key === ARABIC_COFFEE) return "شعبي";
  // ٠٩/١١: كشك القهوة السريع أوّله «درايف»، وشارته «عصائر» (الكافيه ممتلئ).
  if (key === DRIVE_THRU) return "عصائر";
  if (key === TEA_HOUSE) return "شاي";
  if (key === BREAKFAST) return "شعبي";
  if (key === BAKERY) return "مخبز وحلويات";
  if (key === GRILL) return "مشويات";
  if (key === PIZZA) return "مطعم";
  return key;
}

