/**
 * هويّة المنشأة النظامية وما يُشتقّ منها من نصوص — **مصدرٌ واحد**.
 *
 * كانت الضريبة تُقال ثلاث مرّات بثلاث صيغ: «شامل الضريبة» في المساعدة، و«حيثما
 * تنطبق» في الشروط، و«نصدر لك فاتورة ضريبية» في الاشتراك — والمنصّة **بلا رقم
 * ضريبي**. وعدُ فاتورةٍ لا تُصدَر، وادّعاءُ ضريبةٍ لا تُحصَّل، كلاهما مخالفة
 * يُسأل عنها البائع لا الشيفرة.
 *
 * ⚠️ **لا تُخترع هذه القيم.** كل حقل `null` حتى يملأه المالك من وثائقه، وكل
 * نصّ معروض يقرأ الحالة من هنا: بلا رقم ضريبي لا تُذكر ضريبة، ومعه تُذكر
 * «شامل الضريبة» تلقائياً — في كل صفحة معاً.
 */
import { PLANS } from "@/lib/plans";

export type LegalIdentity = {
  /** الاسم النظامي كما في السجل التجاري (أو وثيقة العمل الحر). */
  name: string | null;
  /** رقم السجل التجاري — أو رقم وثيقة العمل الحر. */
  cr: string | null;
  /** الرقم الضريبي (١٥ رقماً) — يبقى `null` ما لم تُسجَّل المنشأة في الضريبة. */
  vat: string | null;
  /** العنوان الوطني المختصر. */
  address: string | null;
  /** بريدٌ للطلبات النظامية والخصوصية. */
  email: string | null;
};

export const LEGAL: LegalIdentity = {
  name: null,
  cr: null,
  vat: null,
  address: null,
  email: null,
};

/** الرقم الضريبي صالح الشكل: ١٥ رقماً تبدأ وتنتهي بـ3 (صيغة الهيئة). */
export const isVatNumber = (v: string | null | undefined): boolean =>
  !!v && /^3\d{13}3$/.test(v.trim());

/** هل المنصّة مسجّلة في ضريبة القيمة المضافة؟ */
export const VAT_REGISTERED = isVatNumber(LEGAL.vat);

/** جملة الضريبة على الاشتراك — الصيغة الوحيدة المسموح عرضها. */
export const SUBSCRIPTION_TAX_NOTE = VAT_REGISTERED
  ? "الأسعار شاملة ضريبة القيمة المضافة ١٥٪."
  : "المنصّة غير مسجّلة في ضريبة القيمة المضافة حالياً، فلا تُحتسب ضريبة على الاشتراك.";

/** هل اكتملت بيانات الهوية؟ (الرقم الضريبي ليس منها — قد لا يلزم.) */
export const IDENTITY_COMPLETE = !!(LEGAL.name && LEGAL.cr && LEGAL.address);

/**
 * نسبة خصم السنوي — **محسوبة** من السعرين لا مكتوبة: كانت الواجهة تقول «شهر
 * مجاني» (أي ٨٪) والسنوي فعلاً ٥٩٩ مقابل ١١٨٨ (أي ٥٠٪). وصفُ الخصم بأقلّ من
 * حقيقته خسارة بيع، وبأكثر منها تضليل — والحساب يمنع الاثنين.
 */
export function yearlyDiscountPct(plan = PLANS[0]): number {
  if (!plan || plan.monthly <= 0) return 0;
  return Math.round((1 - plan.yearly / (plan.monthly * 12)) * 100);
}
