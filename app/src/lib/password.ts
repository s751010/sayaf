/**
 * قوّة كلمة المرور — فحص عند التسجيل وتغيير الكلمة.
 *
 * ═══ لماذا وُجد ═══
 *
 * كان الشرط الوحيد `password.length < 6`. وستّة محارف بلا أي قيد آخر تعني أن
 * «123456» و«aaaaaa» مقبولتان — وهما من أوائل ما تجرّبه أي قائمة تخمين.
 * وحماية كلمات المرور المسرّبة معطّلة في إعدادات Auth (قرار مالك)، **ولا قفل
 * على دخول التاجر** — فكلمة المرور هي الحاجز الوحيد فعلياً.
 *
 * ═══ ⚠️ ما لا يفعله هذا الملفّ ═══
 *
 * **لا يمسّ الحسابات القائمة.** الفحص عند الإنشاء وحده؛ من سجّل بكلمة من ستّة
 * محارف يبقى يدخل بها. تغييرُ ذلك يقفل تجّاراً يعملون اليوم، وهو قرار مالك لا
 * أثر جانبي لتصلّب.
 *
 * ولا يدّعي أنه مقياس إنتروبيا: `zxcvbn` وأمثالها ٤٠٠ كيلوبايت تُحمَّل على
 * صفحة يفتحها زبون المطعم أيضاً (الحزمة الرئيسية). القواعد أدناه تصطاد
 * **الأنماط الشائعة فعلاً** لا كل نمط ممكن.
 */

/** الحدّ الأدنى. ثمانية لا ستّة: كل قائمة توصيات حديثة تبدأ من هنا. */
export const MIN_PASSWORD = 8;

/** كلمات ترد في رؤوس قوائم التخمين — بالعربي والإنجليزي معاً. */
const COMMON = [
  "password", "12345678", "123456789", "qwerty", "111111", "123123",
  "abc123", "iloveyou", "admin", "welcome", "monkey", "letmein",
  "cloudmenu", "menu1234", "restaurant", "1234567890",
];

export type PasswordCheck = {
  ok: boolean;
  /** رسالة الرفض — فارغة عند القبول. */
  error: string;
  /** ٠–٤ لشريط القوّة. */
  score: number;
  label: string;
};

export function checkPassword(pw: string): PasswordCheck {
  const value = pw ?? "";

  if (value.length < MIN_PASSWORD) {
    return {
      ok: false,
      error: `كلمة المرور يجب أن تكون ${MIN_PASSWORD} محارف على الأقل.`,
      score: 0,
      label: "قصيرة جداً",
    };
  }

  const lower = value.toLowerCase();
  if (COMMON.some((c) => lower === c || lower.includes(c))) {
    return {
      ok: false,
      error: "هذه كلمة مرور شائعة جداً — اختر غيرها.",
      score: 0,
      label: "شائعة",
    };
  }

  // محرف واحد مكرّر («aaaaaaaa») أو تسلسل («12345678»).
  if (/^(.)\1+$/.test(value)) {
    return { ok: false, error: "لا تكرّر المحرف نفسه.", score: 0, label: "ضعيفة" };
  }

  /**
   * التنوّع لا التعقيد المفروض: نعدّ **أصناف** المحارف الحاضرة ونطلب اثنين.
   * اشتراط «حرف كبير ورقم ورمز» يدفع الناس إلى `Passw0rd!` — وهو نمط تعرفه
   * كل قائمة تخمين. الطول والتنوّع أنفع من قائمة شروط تُحفَظ.
   *
   * ⚠️ **الأصناف متنافية**: صنف الرموز يستثني العربية صراحةً، وإلا احتُسب
   * النصّ العربي صنفين (رمزاً وعربياً) فمرّت كلمة من صنف واحد. كُشف بفحص
   * «مطعمالديوان» — قُبلت وكان يجب أن تُردّ.
   */
  const classes = [
    /[a-z]/,
    /[A-Z]/,
    /[0-9]/,
    /[؀-ۿ]/,
    /[^a-zA-Z0-9؀-ۿ\s]/,
  ].filter((re) => re.test(value)).length;

  /**
   * ⚠️ **الطول يُغني عن التنوّع عند ١٢ محرفاً فأكثر.**
   *
   * وهذا ليس تساهلاً بل ما تقوله كل توصية حديثة: عبارة طويلة من صنف واحد
   * («مطعمالديوانالرياض») أقوى فعلياً من ثمانية محارف مخلوطة. واشتراط رقمٍ
   * على من يكتب بالعربية وحدها إرباكٌ بلا مقابل أمني.
   */
  const LONG_ENOUGH = 12;
  if (classes < 2 && value.length < LONG_ENOUGH) {
    return {
      ok: false,
      error: `امزج حروفاً وأرقاماً، أو اجعلها ${LONG_ENOUGH} محرفاً فأكثر.`,
      score: 1,
      label: "ضعيفة",
    };
  }

  const score = Math.min(4, classes + (value.length >= LONG_ENOUGH ? 1 : 0) - 1);
  const labels = ["ضعيفة", "مقبولة", "جيدة", "قوية", "قوية جداً"];
  return { ok: true, error: "", score, label: labels[score] ?? "مقبولة" };
}
