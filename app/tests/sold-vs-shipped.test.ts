/**
 * ما يُباع = ما يُسلَّم عند الدفع.
 *
 * ═══ لماذا وُجد هذا الفحص ═══
 *
 * كانت قائمة الباقة تبيع «مفاتيح API وويبهوكات لربط أنظمتك»، والواجهة
 * البرمجية مبنيّة وتعمل فعلاً — لكنها خلف `restaurants.api_enabled` وقيمته
 * الافتراضية في القاعدة `false`. أي أن **الدفع لا يفتحها**: يفتحها المؤسّس
 * لكل مطعم بيده. فالتاجر يقرأ السطر، ويدفع، ثم لا يجد شيئاً في لوحته.
 *
 * وهذا الصنف من العطل لا يمسكه نوعٌ ولا بناء: كلاهما سليم تماماً. يمسكه
 * فحصٌ يسأل سؤالاً تجارياً — **هل ما نَعِد به يُسلَّم؟**
 *
 * والقاعدة: أي ميزة في `features` يجب أن يفتحها الاشتراك وحده. فإن احتاجت
 * مفتاحاً يدوياً من المؤسّس، فهي ليست جزءاً ممّا يُشترى — تُذكر في مكان آخر
 * أو لا تُذكر.
 */
import { describe, expect, it } from "vitest";
import { PLAN } from "@/lib/plans";

describe("قائمة الباقة لا تَعِد بما لا يفتحه الدفع", () => {
  it("لا ذكر للواجهة البرمجية ما دامت خلف مفتاح المؤسّس", () => {
    // `api_enabled` عمودٌ `default false` على `restaurants`، ويقرؤه
    // `Settings.tsx` قبل تركيب `ApiKeysCard` و`WebhooksCard`.
    const sold = PLAN.features.join(" ");
    expect(sold).not.toMatch(/API|ويبهوك|واجهة برمجية/i);
  });

  it("وكل سطرٍ مبيع ليس فارغاً ولا عنصراً نائباً", () => {
    for (const line of PLAN.features) {
      expect(line.trim().length).toBeGreaterThan(8);
      expect(line).not.toMatch(/TODO|قريباً|soon/i);
    }
  });
});
