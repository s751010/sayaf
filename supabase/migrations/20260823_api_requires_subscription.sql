-- الواجهة البرمجية صارت تفحص الاشتراك — وهذا فهرس المسار الساخن
-- ═══════════════════════════════════════════════════════════════════════
--
-- ما كان: `supabase/functions/api/index.ts` تتحقّق من المفتاح ومن حدّ المعدّل
-- ولا تسأل عن اشتراك إطلاقاً. و`api: false` في `FREE_LIMITS` أي أن الواجهة
-- **مقابل اشتراك** — لكن المنع كان في اللوحة وحدها (`ApiKeysCard` تُخفى بلا
-- صلاحية). فمفتاحٌ أُصدر أثناء التجربة يبقى يعمل بعد انتهائها إلى الأبد.
--
-- ما صار: الدالّة تسأل `subscriptions` قبل تنفيذ أي طلب، وتردّ ٤٠٢ إن لم يكن
-- ثمّة اشتراك نشط. أي أن **كل** نداء API صار يحمل استعلامين إضافيين
-- (المطعم ⇐ مالكه، ثم اشتراك المالك) — والحدّ ٦٠ طلباً في الدقيقة لكل مفتاح.
--
-- ولهذا هذا الفهرس: بدونه يمسح Postgres الجدول كاملاً في كل نداء. الجدول
-- اليوم صغير فلا يظهر الفرق، ويظهر يوم يكبر — أي **بعد** أن يصير للتأخير ثمن.
--
-- ⚠️ الشرط هنا يطابق `getActiveSubscription` في الواجهة حرفاً بحرف:
--    `active = true` و`end_date` في المستقبل أو فارغ. أي تباعد بين الاثنين
--    يعني تاجراً يرى «مشترك» في لوحته و«اشترك أوّلاً» في واجهته البرمجية.

-- `CONCURRENTLY` غير مستعمَل عمداً: يُمنع داخل كتلة معاملة، ومهاجر Supabase
-- يلفّ الملفّ في واحدة. والجدول صغير فالقفل لحظيّ.
create index if not exists subscriptions_user_active_idx
  on public.subscriptions (user_id, active, end_date desc);

comment on index public.subscriptions_user_active_idx is
  'المسار الساخن لفحص الاشتراك في دالّة api (§14) — يطابق شرط getActiveSubscription.';

