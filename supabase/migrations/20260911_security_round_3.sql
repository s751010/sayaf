-- ── ١) `phone_key`: تثبيت مسار البحث ───────────────────────────────────
--
-- كانت **الدالّة الوحيدة** في `public` بلا `search_path` مثبَّت — والباقي
-- كلّه `search_path=public`. وهي `SECURITY INVOKER` فلا تصعيد صلاحية فيها،
-- لكنها **تسند فهرساً** (`loyalty_customers_phone_key_idx`): وتعبيرُ فهرس
-- بمسار بحث متغيّر خطرُ صحّة لا تجميل — قد يُحلّ إلى دالّة أخرى بحسب مسار
-- بحث المتصل، فيُبنى الفهرس على معنى ويُستعلم بآخر.
--
-- يُصلحه أيضاً تحذير `function_search_path_mutable` في مستشار Supabase،
-- وهو البند الوحيد القابل للإصلاح برمجياً في تلك القائمة.

alter function public.phone_key(text) set search_path = public;


-- ── ٢) `track_menu_view`: سحب سطحٍ ميّت من `anon` ──────────────────────
--
-- `SECURITY DEFINER` قابلة للنداء من `anon` عبر `/rest/v1/rpc/`، بينما
-- `CLAUDE.md` §2 يصفها «غلاف قديم عليها، **غير مستخدَم**» — والواجهة تنادي
-- `track_view` وحدها. أي سطحٌ مكشوف بلا مستهلك.
--
-- ⚠️ **سحبٌ لا إسقاط في هذه الجولة.** الإسقاط بعد دورة تحقّق: لو ناداها
-- شيء لم يظهر في البحث النصّي، فالسحب يُخرج ٤٠٣ قابلاً للتراجع بسطر —
-- بينما الإسقاط يحتاج إعادة إنشاء. وحُفظ التعريف في التاريخ قبل السحب.

revoke execute on function public.track_menu_view(uuid) from anon, authenticated;


-- ── ٣) فهرس على `orders.user_id` ───────────────────────────────────────
--
-- مفتاح أجنبي بلا فهرس مغطٍّ (`orders_user_id_fkey`) — يرصده مستشار الأداء.
-- الأثر يظهر عند حذف مستخدم أو ضمّ الطلبات إليه، وكلاهما يمسح الجدول كاملاً
-- بلا فهرس.
--
-- ⚠️ **ولا تُسقَط الفهارس السبعة التي يسمّيها المستشار «غير مستعملة».**
-- القاعدة شبه فارغة (صفر طلب)، فـ«غير مستعمل» هنا يعني «لا حركة بعد» لا
-- «خطأ» — وإسقاطها الآن يحذف فهارس ستُستعمل مع أول طلب حقيقي.

create index if not exists orders_user_id_idx on public.orders (user_id);


