/**
 * تهريب قيمة تدخل قالب HTML.
 *
 * ═══ ⚠️ لماذا وُجد ═══
 *
 * قالب بريد تذكرة الدعم كان يحقن `restaurant_name` و`user_name` و`email`
 * و`subject` **بلا أي تهريب**، و`message` وحدها مُهرَّبة تهريباً جزئياً
 * (`<` فقط). فتاجرٌ يسمّي مطعمه `<a href="https://evil">اضغط هنا</a>` يزرع
 * رابط تصيّد في صندوق المالك، **بمظهر بريد رسمي من منصّته**. وعملاء البريد
 * يُسقطون السكربتات لا الروابط ولا المحتوى المخفي.
 *
 * التهريب هنا كامل ويشمل `'` — القالب يستخدم سمات بعلامتين، لكن قاعدة
 * «هرّب كل شيء» لا تعتمد على مراجعة كل موضع إدراج لاحق.
 */
export function escapeHtml(value: unknown): string {
  return String(value ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}
